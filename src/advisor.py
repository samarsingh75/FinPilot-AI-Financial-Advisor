# ------------------------------------------------------------------ goal parsing
_WORD_NUMBERS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8,
    "nine": 9, "ten": 10, "eleven": 11, "twelve": 12, "a": 1, "an": 1,
}
_NUM = r"(\d+(?:\.\d+)?|" + "|".join(_WORD_NUMBERS) + r")"
_DURATION_RE = re.compile(rf"\b{_NUM}\s*[- ]?\s*(months?|years?|yrs?)\b", re.IGNORECASE)
_AMOUNT_RE = re.compile(
    r"(?:(\u20b9|rs\.?|inr)\s*)?(\d[\d,]*(?:\.\d+)?)\s*(k|lakhs?|lacs?|crores?)?(?!\s*(?:months?|years?|yrs?|%|percent))",
    re.IGNORECASE,
)
_MULTIPLIERS = {"k": 1_000, "lakh": 100_000, "lac": 100_000, "crore": 10_000_000}
_GOAL_WORDS = ("save", "saving", "savings", "goal", "target", "afford", "accumulate", "reach", "set aside")


def _first_amount(text: str) -> Optional[float]:
    """First money-like amount in the text (\u20b9/Rs/INR prefix, k/lakh/crore suffix, or >= 1000)."""
    for match in _AMOUNT_RE.finditer(text):
        prefix, digits, multiplier = match.groups()
        value = float(digits.replace(",", ""))
        if multiplier:
            value *= _MULTIPLIERS[multiplier.lower().rstrip("s")]
        if prefix or multiplier or value >= 1000:
            return value
    return None


_PER_MONTH_RE = re.compile(r"(?:\bper\s+month\b|\beach\s+month\b|\bevery\s+month\b|\ba\s+month\b|\bmonthly\b|/\s*month)", re.IGNORECASE)
_SAVE_WORDS = ("save", "saving", "savings", "set aside")


def parse_monthly_savings_target(question: str) -> Optional[float]:
    """Extract a monthly saving target such as 'save \u20b910,000 per month'. Returns the amount or None."""
    text = question or ""
    if not any(w in text.lower() for w in _SAVE_WORDS) or not _PER_MONTH_RE.search(text):
        return None
    return _first_amount(_PER_MONTH_RE.sub(" ", text))


def parse_savings_goal(question: str) -> Optional[dict]:
    """Extract ``{"amount": ..., "months": ...}`` from a question like 'save \u20b950,000 in six months'."""
    text = question or ""
    if not any(word in text.lower() for word in _GOAL_WORDS):
        return None
    duration = _DURATION_RE.search(text)
    if not duration:
        return None
    raw, unit = duration.group(1).lower(), duration.group(2).lower()
    number = float(_WORD_NUMBERS[raw]) if raw in _WORD_NUMBERS else float(raw)
    months = int(round(number * 12)) if unit.startswith(("year", "yr")) else int(round(number))
    if months <= 0:
        return None
    amount = _first_amount(text)
    return {"amount": amount, "months": months} if amount is not None else None


_PERSONAL_RE = re.compile(r"\b(my|mine|our|am i (?:spending|wasting|saving)|do i (?:spend|waste))\b", re.IGNORECASE)


def needs_transaction_data(question: str) -> bool:
    """True when the question is about the user's own finances (so loaded data is required)."""
    return bool(_PERSONAL_RE.search(question or ""))


# ------------------------------------------------------------------ context building
def build_financial_context(
    df: Optional[pd.DataFrame],
    budgets: Optional[dict] = None,
    question: str = "",
    assumed_annual_rate_pct: float = 0.0,
) -> str:
    """Create the text block of ACTUAL figures and HYPOTHETICAL estimates sent to Gemini.

    Privacy: only aggregated figures are included. No transaction descriptions or
    individual transactions are sent.
    """
    if df is None or df.empty:
        return (
            "=== CALCULATED FIGURES ===\n"
            "The user has NOT loaded any transaction data. No personal financial figures are available. "
            "Answer general finance questions only, and say that personalised analysis needs a loaded CSV."
        )

    s = fc.summarize_transactions(df)
    inr = fc.format_inr
    lines = [
        "=== CALCULATED FIGURES (actual values computed by Python from the user's uploaded transactions) ===",
        f"Data period: {s['start_date']} to {s['end_date']} ({s['months_covered']} calendar months with data, "
        f"{s['transaction_count']} transactions)",
        f"Total income: {inr(s['total_income'])}",
        f"Total expenses: {inr(s['total_expenses'])}",
        f"Net savings (income - expenses): {inr(s['net_savings'])}",
        (f"Savings rate: {s['savings_rate_pct']:.1f}%" if s["total_income"] > 0 else "Savings rate: not defined (no income)"),
        f"Average monthly income: {inr(s['average_monthly_income'])}",
        f"Average monthly expenses: {inr(s['average_monthly_expenses'])}",
        f"Average monthly net savings: {inr(s['average_monthly_net_savings'])}",
    ]
    if s["highest_spending_category"]:
        lines.append(f"Highest spending category: {s['highest_spending_category']} ({inr(s['highest_spending_amount'])})")

    categories = fc.category_overview(df).head(10)
    if not categories.empty:
        lines.append("Expense totals by category (largest first):")
        lines += [
            f"  - {r.category}: {inr(r.amount)} total, {r.share_pct:.1f}% of expenses, {r.pct_of_income:.1f}% of income, "
            f"average {inr(r.avg_monthly)} per month"
            for r in categories.itertuples()
        ]

    monthly = fc.monthly_summary(df).tail(12)
    lines.append("Monthly totals:")
    lines += [
        f"  - {r.month}: income {inr(r.income)}, expenses {inr(r.expenses)}, net {inr(r.net_savings)}, "
        f"savings rate {r.savings_rate:.1f}%"
        for r in monthly.itertuples()
    ]

    comparison = ba.compare_budgets(df, budgets or {})
    if comparison.empty:
        lines.append("Budgets: the user has not set any category budgets.")
    else:
        lines.append("Budget comparison (monthly budget vs average monthly actual spending):")
        for r in comparison.itertuples():
            state = f"OVER by {inr(-r.difference)}" if r.actual > r.budget else f"within budget, {inr(r.difference)} left"
            lines.append(f"  - {r.category}: budget {inr(r.budget)}, actual {inr(r.actual)} ({r.percent_used:.0f}% used) -> {state}")
        over = ba.overspent_categories(comparison)
        lines.append("Categories over budget: " + (", ".join(over["category"]) if not over.empty else "none"))

    unusual = fc.unusual_monthly_spending(df).head(5)
    if not unusual.empty:
        lines.append("Unusual spending (calculated: a month well above that category's typical month):")
        lines += [
            f"  - {r.category} in {r.month}: {inr(r.amount)} vs typical {inr(r.typical_monthly)} per month"
            for r in unusual.itertuples()
        ]

    target = parse_monthly_savings_target(question)
    goal = None if target else parse_savings_goal(question)
    if target:
        check = fc.monthly_savings_target_gap(target, s["average_monthly_net_savings"])
        lines += [
            "Monthly saving target check (calculated by Python):",
            f"  - Target: {inr(check['target_monthly'])} per month",
            f"  - Current average monthly net savings: {inr(check['current_avg_monthly_savings'])}",
            "  - Target met at the current rate: " + ("yes" if check["met_at_current_rate"]
                                                      else f"no (extra {inr(check['extra_needed_per_month'])} per month needed)"),
        ]
    if goal:
        result = fc.savings_goal_feasibility(goal["amount"], goal["months"], s["average_monthly_net_savings"])
        needed = result["months_needed_at_current_rate"]
        lines += [
            "Savings goal check (straight-line, no interest, calculated by Python):",
            f"  - Goal: {inr(result['goal_amount'])} in {result['months']} months",
            f"  - Required saving per month: {inr(result['required_monthly_saving'])}",
            f"  - Current average monthly net savings: {inr(result['current_monthly_savings'])}",
            f"  - Achievable at the current savings rate: {'yes' if result['feasible_at_current_rate'] else 'no'}"
            + ("" if result["feasible_at_current_rate"] else f" (monthly shortfall {inr(result['monthly_gap'])})"),
        ]
        if needed:
            lines.append(f"  - Months needed at the current rate: {needed:.1f}")

    lines += ["", "=== HYPOTHETICAL ESTIMATES (assumption-based; NOT actual data and NOT guarantees) ==="]
    monthly_saving = max(s["average_monthly_net_savings"], 0.0)
    lines.append(
        f"Assumption: the user keeps saving {inr(monthly_saving)} per month (their historical average) and earns "
        f"an assumed {assumed_annual_rate_pct:.1f}% annual interest, compounded monthly. Real returns can differ."
    )
    for horizon in (6, 12):
        projection = fc.savings_projection(monthly_saving, horizon, assumed_annual_rate_pct)
        lines.append(f"  - Estimated balance after {horizon} months: {inr(projection['balance'].iloc[-1])}")
    return "\n".join(lines)


def history_pairs(messages: list[dict], max_turns: int = 6) -> list[tuple[str, str]]:
    """Recent complete user/assistant turns, skipping any that ended in an error."""
    pairs: list[tuple[str, str]] = []
    i = 0
    while i < len(messages) - 1:
        a, b = messages[i], messages[i + 1]
        if a["role"] == "user" and b["role"] == "assistant" and not b.get("error"):
            pairs += [("user", a["content"]), ("assistant", b["content"])]
            i += 2
        else:
            i += 1
    return pairs[-2 * max_turns:]


# ------------------------------------------------------------------ Streamlit page
MAX_QUESTION_CHARS = 2000
KB_TOP_K = 3


def _evidence(question: str, top_k: int = KB_TOP_K):
    """Retrieve knowledge-base passages for the question. Returns (chunks, warning_or_None)."""
    from src.knowledge_base_page import get_pipeline
    from src.vector_store import EmbeddingError, VectorStoreError

    try:
        pipeline = get_pipeline()
        return pipeline.retrieve(question, top_k=top_k, min_score=config.DEFAULT_MIN_SCORE), None
    except (EmbeddingError, VectorStoreError) as exc:
        return [], str(exc)
    except Exception as exc:  # noqa: BLE001 - the knowledge base must never break the advisor
        return [], f"Knowledge base unavailable ({type(exc).__name__})."


def answer_question(question: str, df: Optional[pd.DataFrame], budgets: Optional[dict], assumed_rate: float,
                    use_kb: bool, history: Optional[list] = None) -> dict:
    """Build the prompt (calculated figures + optional retrieved passages) and ask Gemini.

    Returns ``{"answer", "sources", "evidence", "kb_note", "prompt"}``. Raises GeminiError on failure.
    """
    from src.rag_pipeline import extract_citations, format_citation, format_context

    chunks, kb_note = _evidence(question) if use_kb else ([], None)
    if use_kb and not chunks and not kb_note:
        kb_note = "No relevant passages were found in your knowledge base, so none were used."
    prompt = build_advisor_prompt(
        question,
        build_financial_context(df, budgets, question, assumed_rate),
        format_context(chunks) if chunks else None,
    )
    answer = GeminiClient().generate(prompt, system_instruction=SYSTEM_PROMPT, history=history or [])
    cited, _ = extract_citations(answer, chunks)
    return {
        "answer": answer,
        "sources": [format_citation(c) for c in cited],
        # Passages that were actually sent to Gemini (never anything that was not retrieved).
        "evidence": [{"citation": f"[{c.rank}] {format_citation(c)}", "text": c.text} for c in chunks],
        "kb_note": kb_note,
        "prompt": prompt,
    }


def _fill_box(text: str) -> None:
    st.session_state["advisor_question"] = text


def _show_message(message: dict) -> None:
    if message.get("error"):
        st.error(message["content"])
        return
    st.markdown(message["content"])
    if message.get("sources"):
        st.caption("Cited sources: " + "; ".join(message["sources"]))
    if message.get("evidence"):
        with st.expander(f"Knowledge-base passages sent to Gemini ({len(message['evidence'])})"):
            for item in message["evidence"]:
                st.markdown(f"**{item['citation']}**")
                st.write(item["text"])
    if message.get("kb_note"):
        st.caption(message["kb_note"])
    st.caption(DISCLAIMER)


def render() -> None:
    st.session_state.setdefault("chat", [])
    if st.session_state.pop("_advisor_clear_box", False):  # clear the box AFTER a successful answer
        st.session_state["advisor_question"] = ""
    df = st.session_state.get("transactions")
    budgets = st.session_state.get("budgets", {})

    configured = is_configured()
    if not configured:
        st.warning(
            "**Gemini is not configured.** Questions cannot be sent, but you can still inspect the data that would be "
            "sent. Add your key to the `.env` file as `GEMINI_API_KEY` (see README) and restart the app."
        )
    if df is None:
        st.info("No transaction data is loaded. Load the sample data (or your CSV) on the **Financial Dashboard** page for "
                "personalised answers. General finance questions still work.")
    else:
        st.caption(f"Using the currently loaded data: **{st.session_state.get('data_source', 'your dataset')}** "
                   f"({len(df)} transactions).")

    with st.sidebar:
        st.markdown("#### Advisor settings")
        rate = st.number_input(
            "Assumed annual interest rate for estimates (%)", min_value=0.0, max_value=20.0, value=4.0, step=0.5,
            help="A hypothetical assumption used only in clearly labelled estimates. It is not a forecast.",
        )
        from src.knowledge_base_page import get_store

        try:
            store = get_store()
            kb_has_docs = not store.is_empty
            kb_docs = store.document_count
        except Exception:  # noqa: BLE001
            kb_has_docs, kb_docs = False, 0
        use_kb = st.checkbox(
            "Use my knowledge base as evidence", value=True, disabled=not kb_has_docs, key="advisor_use_kb",
            help="Adds the most relevant indexed passages to the prompt and lets the model cite them.",
        ) and kb_has_docs
        if kb_has_docs:
            st.caption(f"Knowledge base ready: {kb_docs} document(s). No re-indexing needed.")
        else:
            st.caption("No documents indexed yet. Index them on the RAG Knowledge Base page to enable this.")

    top_l, top_r = st.columns([4, 1])
    top_l.caption(f"Model: `{config.get_model_name()}`  |  " + ("API key: configured" if configured else "API key: missing"))
    if top_r.button("Reset conversation", width="stretch"):
        st.session_state["chat"] = []
        st.session_state.pop("last_prompt", None)
        st.rerun()

    with st.expander("Inspect the data that will be sent to Gemini", expanded=False):
        st.markdown(
            "Only the **summary figures below**, any retrieved knowledge-base passages, and your question are sent to "
            "Google's Gemini API. Transaction descriptions and individual transactions are **not** sent."
        )
        st.markdown("**System prompt**")
        st.code(SYSTEM_PROMPT, language="text")
        st.markdown("**Financial context (computed locally; your question may add goal calculations)**")
        st.code(build_financial_context(df, budgets, "", rate), language="text")
        if st.session_state.get("last_prompt"):
            st.markdown("**Full prompt of the most recent question**")
            st.code(st.session_state["last_prompt"], language="text")

    # ---------------------------------------------------------------- input
    st.markdown("#### Ask your own question")
    st.caption("Type anything about your finances in plain English, or click an idea to fill the box and edit it.")
    cols = st.columns(2)
    for i, example in enumerate(EXAMPLE_QUESTIONS):
        cols[i % 2].button(example, key=f"ex_{i}", on_click=_fill_box, args=(example,), width="stretch")
    st.text_area(
        "Your question", key="advisor_question", height=120, label_visibility="collapsed",
        placeholder="e.g. Analyze my spending and identify where I waste the most money.",
    )
    ask = st.button("Ask Advisor", type="primary", disabled=not configured)

    if ask:
        question = (st.session_state.get("advisor_question") or "").strip()
        failed = False
        if not question:
            st.warning("Please type a question before clicking Ask Advisor.")
        elif len(question) > MAX_QUESTION_CHARS:
            st.warning(f"Your question is too long. Please keep it under {MAX_QUESTION_CHARS} characters.")
        elif df is None and needs_transaction_data(question):
            st.error("This question is about your own finances, but no transaction data is loaded. Load the sample "
                     "dataset or upload your CSV on the **Financial Dashboard** page, then ask again.")
        else:
            history = history_pairs(st.session_state["chat"])
            st.session_state["chat"].append({"role": "user", "content": question})
            try:
                with st.spinner("Gemini is analysing your data and writing the answer..."):
                    result = answer_question(question, df, budgets, rate, use_kb, history)
            except GeminiError as exc:
                failed = True
                st.session_state["chat"].append({"role": "assistant", "content": exc.message, "error": True})
            except Exception as exc:  # noqa: BLE001 - keep the page alive
                failed = True
                st.session_state["chat"].append(
                    {"role": "assistant", "error": True,
                     "content": f"Something unexpected went wrong ({type(exc).__name__}). Please try again."})
            else:
                st.session_state["last_prompt"] = result["prompt"]
                st.session_state["chat"].append({
                    "role": "assistant", "content": result["answer"], "sources": result["sources"],
                    "evidence": result["evidence"], "kb_note": result["kb_note"],
                })
                st.session_state["_advisor_clear_box"] = True
            if failed:
                st.caption("Your question is still in the box so you can try again.")
            else:
                st.rerun()

    # ---------------------------------------------------------------- history (newest first)
    chat = st.session_state["chat"]
    pairs = list(zip(chat[0::2], chat[1::2]))
    if pairs:
        st.markdown("#### Conversation")
    for user_msg, assistant_msg in reversed(pairs):
        with st.chat_message("user"):
            st.markdown(user_msg["content"])
        with st.chat_message("assistant"):
            _show_message(assistant_msg)
